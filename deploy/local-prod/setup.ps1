<#
.SYNOPSIS
  One-time setup of the LOCAL production deployment: database `asaa`, separate migrator/runtime roles, secrets and signing keys.

.DESCRIPTION
  * Prompts for the PostgreSQL superuser password (SecureString). It is kept only in this process environment and is never written to disk.
  * Creates database asaa and the roles asaa_migrator (owns the schema) and asaa_runtime (row access only) with scripts/db_roles.py.
  * Generates the role passwords, a metrics token and an RSA key pair, and writes them to the git-ignored .env.local-prod and
    .local-prod\keys with an ACL limited to the current user. Re-running keeps existing secrets (idempotent).
  * Nothing is deployed and nothing leaves this machine.

.PARAMETER PgHost / PgPort   PostgreSQL service as seen from this machine (containers reach it as host.docker.internal).
.PARAMETER PgAdminUser       Superuser name (default postgres).
.PARAMETER ConfigureHba      Also append scoped scram-sha-256 lines for Docker Desktop networks to pg_hba.conf (needs an elevated shell) and reload.
#>
[CmdletBinding()]
param(
  [string]$PgHost = '127.0.0.1',
  [int]$PgPort = 5432,
  [string]$PgAdminUser = 'postgres',
  [string]$DbName = 'asaa',
  [string]$PgService = 'postgresql-x64-18',
  [string]$PgBin = 'C:\Program Files\PostgreSQL\18\bin',
  [int]$PortalPort = 8100,
  [int]$ApiPort = 8101,
  [switch]$ConfigureHba
)
. (Join-Path $PSScriptRoot 'common.ps1')
$me = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name

function New-Secret([int]$bytes = 24) {
  $b = New-Object byte[] $bytes
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
  return (($b | ForEach-Object { $_.ToString('x2') }) -join '')
}
function Restrict-Acl([string]$path) {
  & icacls.exe $path /inheritance:r /grant:r "${me}:(F)" | Out-Null
  if ($LASTEXITCODE -ne 0) { throw "could not restrict the ACL on $path" }
}

# 1. PostgreSQL must be listening.
function Test-Port { try { $c = New-Object Net.Sockets.TcpClient; $c.Connect($PgHost, $PgPort); $c.Close(); return $true } catch { return $false } }
if (-not (Test-Port)) {
  $svc = Get-Service -Name $PgService -ErrorAction SilentlyContinue
  if ($svc -and $svc.Status -ne 'Running') { Start-Service $PgService; Start-Sleep -Seconds 5 }
}
if (-not (Test-Port)) { throw "PostgreSQL is not reachable at ${PgHost}:$PgPort. Start the $PgService Windows service (services.msc, as administrator) and re-run." }

# 2. Python environment (isolated venv, locked to the API constraints).
New-Item -ItemType Directory -Force $StateDir | Out-Null
$venvPy = Join-Path $StateDir 'venv\Scripts\python.exe'
if (-not (Test-Path $venvPy)) {
  $made = $false
  $candidates = @()
  if ($env:ASAA_PYTHON) { $candidates += ,@($env:ASAA_PYTHON) }
  foreach ($v in '3.12', '3.13', '3.11', '3.14', '3') { $candidates += ,@('py', "-$v") }
  foreach ($c in $candidates) {
    $exe = $c[0]; $extra = @($c | Select-Object -Skip 1)
    try {
      $ver = & $exe @extra -c 'import sys; print(sys.version_info >= (3, 11))' 2>$null
      if ($LASTEXITCODE -ne 0 -or $ver -ne 'True') { continue }
      & $exe @extra -m venv (Join-Path $StateDir 'venv')
      if ($LASTEXITCODE -eq 0) { $made = $true; break }
    } catch { continue }
  }
  if (-not $made) { throw 'No working Python 3.11+ found. Install one or set ASAA_PYTHON to its python.exe.' }
}
& $venvPy -c "import psycopg, jwt, cryptography" 2>$null
if ($LASTEXITCODE -ne 0) {
  Invoke-Native $venvPy @('-m', 'pip', 'install', '--quiet', '-c', (Join-Path $Repo 'apps\ap-api\constraints.txt'), 'psycopg[binary]', 'PyJWT[crypto]')
}

# 3. Secrets (kept when they already exist).
$existing = if (Test-Path $EnvFile) { Read-EnvFile } else { @{} }
function Pick($key, $make) { if ($existing.ContainsKey($key) -and $existing[$key]) { return $existing[$key] } return (& $make) }
$migratorPw = Pick 'ASAA_DB_MIGRATOR_PASSWORD' { New-Secret }
$runtimePw = Pick 'ASAA_DB_RUNTIME_PASSWORD' { New-Secret }
$metricsToken = Pick 'ASAA_METRICS_TOKEN' { New-Secret }
$lines = @(
  '# Generated by deploy/local-prod/setup.ps1. LOCAL production only. Git-ignored. Do not share.',
  "ASAA_PG_HOST=$PgHost", "ASAA_PG_PORT=$PgPort", "ASAA_DB_NAME=$DbName",
  'ASAA_DB_MIGRATOR_ROLE=asaa_migrator', "ASAA_DB_MIGRATOR_PASSWORD=$migratorPw",
  'ASAA_DB_RUNTIME_ROLE=asaa_runtime', "ASAA_DB_RUNTIME_PASSWORD=$runtimePw",
  "ASAA_METRICS_TOKEN=$metricsToken", "PORTAL_PORT=$PortalPort", "API_PORT=$ApiPort")
[System.IO.File]::WriteAllText($EnvFile, (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding($false)))
Restrict-Acl $EnvFile

& $venvPy (Join-Path $PSScriptRoot 'tools.py') keygen --out-dir (Join-Path $StateDir 'keys')
if ($LASTEXITCODE -ne 0) { throw 'key generation failed' }
Restrict-Acl (Join-Path $StateDir 'keys\jwt_private.pem')

# 4. Database and roles. The superuser password lives only in this process.
# Interactive by default. ASAA_PG_ADMIN_PASSWORD is an automation/rehearsal escape hatch that is read from the environment only (never written anywhere).
$bstr = [IntPtr]::Zero
if ($env:ASAA_PG_ADMIN_PASSWORD) { $adminPassword = $env:ASAA_PG_ADMIN_PASSWORD }
else {
  $secure = Read-Host -AsSecureString "PostgreSQL password for '$PgAdminUser' (not stored)"
  $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
  $adminPassword = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
}
try {
  $env:PGPASSWORD = $adminPassword
  $env:ASAA_DB_MIGRATOR_PASSWORD = $migratorPw
  $env:ASAA_DB_RUNTIME_PASSWORD = $runtimePw
  $tools = Join-Path $PSScriptRoot 'tools.py'
  & $venvPy $tools ensure-db --admin-url "postgresql://${PgAdminUser}@${PgHost}:$PgPort/postgres" --name $DbName
  if ($LASTEXITCODE -ne 0) { throw 'could not create the database (wrong superuser password?)' }
  & $venvPy (Join-Path $Repo 'apps\ap-api\scripts\db_roles.py') provision --admin-url "postgresql://${PgAdminUser}@${PgHost}:$PgPort/$DbName"
  if ($LASTEXITCODE -ne 0) { throw 'role provisioning failed' }

  if ($ConfigureHba) {
    $hba = & (Join-Path $PgBin 'psql.exe') -h $PgHost -p $PgPort -U $PgAdminUser -d postgres -tAc 'SHOW hba_file'
    Copy-Item $hba "$hba.asaa-backup" -Force
    $rules = "`n# ASAA local production (Docker Desktop networks only)`nhost $DbName asaa_migrator,asaa_runtime 172.16.0.0/12 scram-sha-256`nhost $DbName asaa_migrator,asaa_runtime 192.168.0.0/16 scram-sha-256`n"
    if (-not (Select-String -Path $hba -Pattern 'ASAA local production' -Quiet)) { Add-Content -Path $hba -Value $rules }
    & (Join-Path $PgBin 'psql.exe') -h $PgHost -p $PgPort -U $PgAdminUser -d postgres -tAc 'SELECT pg_reload_conf()' | Out-Null
    Write-Host "pg_hba.conf updated (backup: $hba.asaa-backup) and reloaded."
  }
} finally {
  $env:PGPASSWORD = $null
  $env:ASAA_DB_MIGRATOR_PASSWORD = $null
  $env:ASAA_DB_RUNTIME_PASSWORD = $null
  if ($bstr -ne [IntPtr]::Zero) { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }
  $adminPassword = $null
}

# 5. Can a container reach the host database?
docker image inspect postgres:16 *> $null
if ($LASTEXITCODE -eq 0) {
  docker run --rm --add-host host.docker.internal:host-gateway postgres:16 pg_isready -h host.docker.internal -p $PgPort *> $null
  if ($LASTEXITCODE -ne 0) {
    Write-Warning "Containers cannot reach PostgreSQL at host.docker.internal:$PgPort. Set listen_addresses = '*' in postgresql.conf and re-run this script with -ConfigureHba from an elevated shell (or add the pg_hba lines yourself), then restart the $PgService service."
  }
}
Write-Host "Setup complete. Next: deploy\local-prod\up.ps1   (login token: deploy\local-prod\mint-token.ps1)"
